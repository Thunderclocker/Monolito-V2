def update_domain_imports():
    """For each domain file, add the appropriate imports from internal.ts."""
    for domain_file in sorted(DOMAINS_DIR.glob("*.ts")):
        text = domain_file.read_text()
        # Find existing import lines
        lines = text.split("\n")
        # Replace the simple import with the new one
        new_lines = []
        skip_old_import = False
        for line in lines:
            if line.strip() == 'import type { ToolDefinition } from "../registry.ts"':
                skip_old_import = True
                continue
            new_lines.append(line)
        # Find used identifiers
        used = find_used_identifiers_in_domain(domain_file)
        # Build the new import statements
        if not used:
            print(f"  {domain_file.name}: no helpers used?")
            domain_file.write_text("\n".join(new_lines))
            continue
        # Split into helpers from internal.ts vs imports from registry.ts
        # For now, all of them are expected to be in internal.ts.
        # Sort and format
        helpers = sorted(used - {"ToolDefinition"})
        # Check if ToolDefinition is also in there
        imports_block = ['import type { ToolDefinition } from "../registry.ts"']
        if helpers:
            imports_block.append('import {')
            for h in helpers:
                imports_block.append(f"  {h},")
            imports_block.append("} from \"./internal.ts\"")
        # Find the spot to insert (after the first comment lines)
        # Original file starts with:
        #   // Auto-generated comment
        #   // Domain: ...
        #   (blank)
        #   import type { ToolDefinition } from "../registry.ts"
        #   (blank)
        #   export const ...
        # We want to replace the import line with our new imports.
        result = []
        for line in new_lines:
            if line.startswith("export const "):
                # Insert our imports before this line
                result.extend(imports_block)
                result.append("")
                result.append(line)
            else:
                result.append(line)
        # Make sure imports are at the top (after the first comments)
        # Re-do: filter out the now-redundant imports
        final = []
        in_imports = False
        imports_done = False
        for line in result:
            if not imports_done and line.startswith("import "):
                # Skip existing import lines (we'll add them back together)
                in_imports = True
                continue
            if in_imports and line.strip() == "":
                in_imports = False
                # Add the imports here
                final.extend(imports_block)
                final.append("")
                imports_done = True
                continue
            if in_imports:
                continue  # skip
            final.append(line)
        domain_file.write_text("\n".join(final))
        print(f"  {domain_file.name}: added {len(helpers)} helper imports")

if __name__ == "__main__":
    extract_helpers()
    print("\n=== Updating domain imports ===")
    update_domain_imports()
