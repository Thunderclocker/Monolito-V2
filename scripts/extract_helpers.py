"""
Extracts the helper section (lines 1-1080) of registry.ts to internal.ts,
adding `export` to every function, const, etc. Also generates the
import statements for each domain file.

This is a one-time refactor script.
"""

import re
from pathlib import Path

REGISTRY = Path("src/core/tools/registry.ts")
INTERNAL = Path("src/core/tools/internal.ts")
DOMAINS_DIR = Path("src/core/tools/domains")

# Lines 1-1080 are the helpers (per analysis). The const rawTools starts at 1081.
# We extract everything UP TO the line before "const rawTools".
HELPERS_END_LINE = 1080  # 0-based exclusive: read up to line 1080 (1-based 1080)

# All helpers we know about (functions, consts, etc.) that need to be exported.
# We add `export` to anything that doesn't already have it.
EXPORT_TARGETS = {
    "function", "const", "async function", "let",
}

def add_export_to_declarations(text: str) -> str:
    """Add `export` keyword to function/const declarations that don't have it."""
    out_lines = []
    for line in text.split("\n"):
        stripped = line.lstrip()
        # If line already starts with `export`, skip
        if stripped.startswith("export "):
            out_lines.append(line)
            continue
        # Match function declarations
        m = re.match(r'^(\s*)(async\s+function\s+\w+|function\s+\w+)', line)
        if m:
            indent = m.group(1)
            rest = line[len(indent):]
            out_lines.append(f"{indent}export {rest}")
            continue
        # Match const/let declarations (with or without type annotation)
        m = re.match(r'^(\s*)(const|let)\s+(\w+)', line)
        if m:
            indent = m.group(1)
            kind = m.group(2)
            name = m.group(3)
            # Skip if it's a destructured import (would have been `import`)
            rest = line[len(indent):]
            out_lines.append(f"{indent}export {rest}")
            continue
        out_lines.append(line)
    return "\n".join(out_lines)


def extract_helpers():
    text = REGISTRY.read_text()
    lines = text.split("\n")
    # Lines are 0-based. Line 1080 (0-based) is the line BEFORE `const rawTools: ...` at line 1081 (0-based 1080).
    # The line before "const rawTools:" is what we want.
    # Find exact line
    for i, line in enumerate(lines):
        if re.match(r'^const rawTools: ToolDefinition\[\] = \[$', line):
            helpers_end = i  # exclusive
            break
    else:
        raise SystemExit("Could not find rawTools array start")
    print(f"Helpers span lines 1 to {helpers_end} (0-based)")

    helpers_text = "\n".join(lines[:helpers_end])
    helpers_text = add_export_to_declarations(helpers_text)

    # Wrap the internal.ts in a clear header
    header = """// Shared internal helpers for the tool registry and domain files.
// This file is auto-generated by scripts/extract_helpers.py — do not edit
// manually except to add new exports. Domain files in ./domains/ import
// from here. registry.ts re-exports the public API.

"""
    INTERNAL.write_text(header + helpers_text)
    print(f"Wrote {INTERNAL} ({len(helpers_text.split(chr(10)))} lines)")

